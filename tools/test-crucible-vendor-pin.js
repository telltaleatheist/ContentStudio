/**
 * THE VENDORED SDK IS WHAT THE PIN SAYS, AND THE MODULE IS WHAT ITS GENERATOR WROTE.
 *
 * The pin is written in four places that do not look alike (two `file:vendor/`
 * dependency lines, two `//crucible-*` prose keys) plus two tarballs on disk,
 * and a package that installs can still describe a release it is not pinned
 * to (the failure BookForge's install-seam keeper and Briefcase's
 * sdk-seam.spec.ts were written for). So: the adopt script's own reader finds
 * one version in package.json, both tarballs of that version are the only ones
 * in vendor/, the installed packages report it, and the prose names it.
 *
 * The module (shared/crucible/contentstudio.module.json) is generated by the
 * crucible release's own gen-modules.py and vendored byte for byte (plan
 * section 3.4, section 0a "Mechanics"). Its `version` is `<crucible>+<hash of
 * its own content>`, recomputed here the way crucible/modules.py `version_of`
 * computes it, so a hand edit is caught; its crucible half must be the pinned
 * release; its bytes must be the generator's rendering; and its ids must be
 * the ones its declaration (contentstudio.toml) names.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const { assert, crucible, check, run, REPO } = require('./_crucible-keeper');

const manifest = JSON.parse(fs.readFileSync(path.join(REPO, 'package.json'), 'utf8'));

async function adoptScript() {
  return import(pathToFileURL(path.join(REPO, 'tools', 'adopt-crucible-release.mjs')).href);
}

check('both packages are pinned file:vendor/ at ONE version, read by the adopt script\'s own reader', async () => {
  const adopt = await adoptScript();
  const pinned = adopt.pinnedVersion(manifest);
  assert.match(pinned, /^\d+\.\d+\.\d+$/);
  assert.strictEqual(manifest.dependencies['@crucible/client'], `file:vendor/crucible-client-${pinned}.tgz`);
  assert.strictEqual(manifest.dependencies['@crucible/bootstrap'], `file:vendor/crucible-bootstrap-${pinned}.tgz`);
});

check('vendor/ holds exactly the two pinned tarballs, and nothing stale', async () => {
  const pinned = (await adoptScript()).pinnedVersion(manifest);
  assert.deepStrictEqual(fs.readdirSync(path.join(REPO, 'vendor')).sort(), [`crucible-bootstrap-${pinned}.tgz`, `crucible-client-${pinned}.tgz`]);
});

check('the installed packages report the pinned version, and so do their own version constants', async () => {
  const pinned = (await adoptScript()).pinnedVersion(manifest);
  assert.strictEqual(require('@crucible/client/package.json').version, pinned);
  assert.strictEqual(require('@crucible/bootstrap/package.json').version, pinned);
  assert.strictEqual(require('@crucible/client').SDK_VERSION, pinned);
  assert.strictEqual(require('@crucible/bootstrap').BOOTSTRAP_VERSION, pinned);
});

check('the //crucible-* prose names the pinned release and no other', async () => {
  const pinned = (await adoptScript()).pinnedVersion(manifest);
  const prose = Object.entries(manifest).filter(([key]) => key.startsWith('//crucible'));
  assert.strictEqual(prose.length, 2);
  for (const [key, text] of prose) {
    const versions = [...new Set(text.match(/\d+\.\d+\.\d+/g))];
    assert.deepStrictEqual(versions, [pinned], key);
  }
});

check('the packaged app carries the module file', () => {
  assert.ok(manifest.build.files.includes('shared/crucible/*.module.json'));
});

// ── the module ──────────────────────────────────────────────────────────────

const MODULE_DIR = path.join(REPO, 'shared', 'crucible');
const moduleText = fs.readFileSync(path.join(MODULE_DIR, 'contentstudio.module.json'), 'utf8');
const moduleDoc = JSON.parse(moduleText);

/** Python's json.dumps(sort_keys=True, separators=(',', ':')), for the ASCII this module holds. */
function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
  if (value !== null && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

check('the module\'s version is <pinned crucible>+<hash of its own content> (crucible/modules.py version_of)', async () => {
  const pinned = (await adoptScript()).pinnedVersion(manifest);
  const { version, ...rest } = moduleDoc;
  const body = { name: rest.name, job_types: rest.job_types, needs: rest.needs, subjects: rest.subjects };
  const digest = crypto.createHash('sha256').update(canonical(body), 'utf8').digest('hex').slice(0, 12);
  assert.strictEqual(version, `${pinned}+${digest}`);
});

check('the module\'s bytes are the generator\'s rendering (json.dumps indent=2 plus a newline): no hand edit', () => {
  assert.strictEqual(moduleText, `${JSON.stringify(moduleDoc, null, 2)}\n`);
});

check('the module names what its declaration names, with the 1.0.29+ ids and no retired one', () => {
  const toml = fs.readFileSync(path.join(MODULE_DIR, 'contentstudio.toml'), 'utf8');
  const uncommented = toml.split('\n').filter((line) => !line.trim().startsWith('#')).join('\n');
  const declared = (key) => [...uncommented.matchAll(new RegExp(`^${key} = "([^"]+)"`, 'gm'))].map((m) => m[1]);
  assert.deepStrictEqual(moduleDoc.job_types.map((j) => j.type), declared('type'));
  assert.deepStrictEqual(moduleDoc.needs.map((n) => n.class), declared('class'));
  assert.deepStrictEqual(moduleDoc.subjects.map((s) => s.id), declared('id'));
  // P7: `rvc` installs the env `denoise` runs in, and the vocals separator is the editor's (LEDGER #200).
  assert.deepStrictEqual(moduleDoc.job_types.map((j) => j.type), ['llm', 'asr', 'align', 'rvc']);
  assert.deepStrictEqual(moduleDoc.subjects.map((s) => s.id), ['qwen3-asr-1.7b', 'qwen3-aligner', 'qwen3.8-27b-4bit', 'qwen3.5-9b', 'vocals-roformer']);
  // LEDGER #205 / plan 21 Q15: the official id, never the -mlx port; and no retired whisper id.
  assert.ok(!moduleText.includes('-mlx'));
  assert.ok(!/mlx-whisper|faster-whisper/.test(moduleText));
});

check('moduleForBackend strips `backends` and filters to one backend; an unstated backend is refused by name', () => {
  const { readVendoredModule, moduleForBackend } = crucible('module-setup');
  const vendored = readVendoredModule(path.join(MODULE_DIR, 'contentstudio.module.json'));
  const mac = moduleForBackend(vendored, 'mlx-darwin', 'mac');
  assert.ok(!JSON.stringify(mac).includes('backends'));
  assert.deepStrictEqual(mac.job_types.map((j) => j.type), ['llm', 'asr', 'align', 'rvc']);
  const windows = moduleForBackend(vendored, 'llama-windows', 'pc');
  // The native Windows engine serves llm only; asr and align need WSL (INTEGRATING-AN-APP.md section 11).
  assert.deepStrictEqual(windows.job_types.map((j) => j.type), ['llm']);
  assert.deepStrictEqual(windows.subjects.map((s) => s.id), ['qwen3.8-27b-4bit', 'qwen3.5-9b']);
  assert.throws(() => moduleForBackend(vendored, null, 'lean'), /did not state host\.backend/);
});

run('crucible: the vendored SDK equals the pin, and the module is the generator\'s');
